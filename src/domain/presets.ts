function p(
  id: string,
  name: string,
  genre: string,
  chart: string,
  key: number,
  bpm: number,
  drumPattern: string,
  keysPattern: string,
  description: string,
  tip: string,
  tags: string,
  options: Pick<Partial<Setup>, "minor" | "bassMotion"> &
    Pick<NonNullable<Setup["metadata"]>, "genres" | "moods" | "difficulty"> = {},
): Omit<Arrangement, "mode" | "mix" | "master" | "countIn" | "metronome" | "showScale"> {
  return {
    id,
    name,
    category: genre,
    description,
    chords: chart.split(" "),
    key,
    minor: options.minor ?? false,
    bpm,
    style: styles[drumPattern],
    drumPattern,
    bassMotion: options.bassMotion ?? "roots",
    keysPattern,
    tip,
    metadata: {
      genres: [genre, ...(options.genres ?? [])],
      moods: options.moods ?? ["focused"],
      tags: tags.split("|"),
      difficulty: options.difficulty ?? "intermediate",
    },
  };
}

